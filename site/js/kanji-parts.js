/** KanjiVG SVG text → the kanji's direct components (deduplicated, in order). [] when it has none.
 *  A group with kvg:element is a component (its inner groups are not looked at); a group without one is looked inside. */
export function partsFromSVG(text, ch) {
  const hex = ch.codePointAt(0).toString(16).padStart(5, '0');
  const start = String(text).indexOf(`<g id="kvg:${hex}"`);
  if (start < 0) return [];
  const out = [];
  const re = /<g\b([^>]*)>|<\/g>/g;
  re.lastIndex = start;
  let depth = 0, inside = 0; // inside = depth of the component being skipped (0 = none)
  for (let m; (m = re.exec(text));) {
    if (m[0] === '</g>') { if (inside === depth) inside = 0; if (--depth === 0) break; continue; }
    depth++;
    if (depth === 1 || inside) continue;
    const el = /kvg:element="([^"]+)"/.exec(m[1]);
    if (el && el[1] !== ch) { if (!out.includes(el[1]) && !el[1].startsWith('CDP')) out.push(el[1]); inside = depth; } // CDP-xxxx = KanjiVG-internal glyph id
  }
  return out;
}

/** [{ ch, uk }] — meanings from the kanji list first (meaningOf(ch) → string|''), then the component table. */
export const partsWithMeanings = (parts, meaningOf = () => '') => parts.map(ch => ({ ch, uk: meaningOf(ch) || PART_UK[ch] || '' }));
